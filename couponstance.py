import asyncio
import logging
import os
import random

import dotenv
from playwright.async_api import async_playwright

# Load the .env
dotenv.load_dotenv()

# Get the directory where the script is located
script_dir = os.path.dirname(os.path.abspath(__file__))

# Configure logging
log_file = os.path.join(script_dir, 'app.log')
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    datefmt='%Y-%m-%d %H:%M:%S',
    handlers=[
        logging.FileHandler(log_file),
        logging.StreamHandler()
    ]
)

uid_list = os.getenv("TRICKAL_UID", "").split(',')

# 트릭컬 리바이브 URL
BASE_URL = 'https://game.naver.com'
# 쿠폰 게시판 URL
COUPON_NOTICE_BOARD_URL = 'https://game.naver.com/lounge/Trickcal/board/31'
# IOS 쿠폰 입력 페이지
IOS_COUPON_URL = 'https://coupon.a.prod.service.trickcal.io/'
# UID
UID_LIST = os.getenv("TRICKAL_UID", "").split(',')
UID_LIST = [uid.strip() for uid in UID_LIST if uid.strip()]

THREAD_COUPON_TITLE = "[쿠폰]"
COUPON_HEADER = "쿠폰 코드(대소문자를 구분합니다)"
COUPON_MESSAGE_COOLDOWN= "쿠폰 입력 쿨타임 중입니다.잠시 후 다시 이용해주세요."
COUPON_MESSAGE_ALREADY_USED = "이미 사용된 쿠폰입니다."
MAX_RETRIES = 3


# Get the link
async def extract_coupon_link(page):
    # Navigate to the coupon board
    await page.goto(COUPON_NOTICE_BOARD_URL, wait_until='load')

    # Wait for content to load (adjust selector as needed)
    await page.wait_for_selector('a[class*="post_board_title"]', state='visible')

    # Query for <a> tag with class containing "post_board_title" AND text containing "[쿠폰]"
    post_link_elem = await page.query_selector(f'a[class*="post_board_title"]:has-text("{THREAD_COUPON_TITLE}")')

    if post_link_elem:
        post_href = await post_link_elem.get_attribute('href')
        full_url = BASE_URL + post_href
        logging.info(f"Found coupon link: {full_url}")
        return full_url
    else:
        logging.info("No coupon link found")
        return None


# Assuming you're already on the target page
async def extract_coupon_code(page, full_url):
    # Load page
    await page.goto(full_url, wait_until='load')
    # Step 1: Find the <p> that has a <span> containing "쿠폰 코드"
    # Using locator and exact text match with filtering
    coupon_label = await page.locator('p').filter(has_text=COUPON_HEADER).first.element_handle()

    if not coupon_label:
        logging.info(f"❌ '{COUPON_HEADER}' not found in any <p>")
        return None

    # Step 2: Get the very next <p> sibling (adjacent sibling)
    next_p = await page.evaluate_handle(
        """(el) => {
            const next = el.nextElementSibling;
            return next && next.tagName === 'P' ? next : null;
        }""",
        coupon_label
    )

    if not next_p or await next_p.evaluate("e => !e"):
        logging.info("❌ No next <p> found")
        return None

    # Step 3: Extract text from span inside next <p>
    coupon_code = await next_p.evaluate("""(p) => {
        return p.querySelector('span')?.innerText.trim();
    }""")

    await next_p.dispose()

    if coupon_code:
        logging.info(f"✅ Coupon code: {coupon_code}")
        return coupon_code
    else:
        logging.info("❌ Empty or no span text")
        return None


async def human_like_delay(min_ms=100, max_ms=500):
    """Add a random delay to mimic human behavior."""
    await asyncio.sleep(random.uniform(min_ms / 1000, max_ms / 1000))


async def submit_coupon(page, uid, coupon_code):
    """Submit coupon for a given UID."""
    logging.info(f"Entrying Coupon for ID: {uid}")
    await page.goto(IOS_COUPON_URL, wait_until='load')

    # Simulate human-like behavior
    await human_like_delay(500, 1500)
    await page.mouse.move(random.randint(100, 500), random.randint(100, 500))
    await page.locator('#UserId').type(uid, delay=random.randint(50, 150))
    await human_like_delay(300, 1000)
    await page.locator('#CouponCode').type(coupon_code, delay=random.randint(50, 150))

    await human_like_delay(500, 1500)
    await page.click('button[onclick="CouponSubmit()"]')
    await human_like_delay(1000, 3000)

    # Get result message
    result = await page.locator('#result-message').text_content()
    logging.info(f"Result for UID {uid}: {result}")
    return result


async def submit_coupon_with_retry(page, uid, coupon_code):
    """Submit coupon with retry logic for cooldown."""
    for attempt in range(MAX_RETRIES):
        result = await submit_coupon(page, uid, coupon_code)
        if "쿨타임" in result:
            wait_time = (2 ** attempt) * 30  # Exponential backoff: 30s, 60s, 120s
            logging.info(
                f"Cooldown detected for UID {uid}, attempt {attempt + 1}/{MAX_RETRIES}. Waiting {wait_time} seconds...")
            await human_like_delay(wait_time * 1000, (wait_time + 5) * 1000)
        else:
            return result
    logging.error(f"Failed to submit coupon for UID {uid} after {MAX_RETRIES} attempts")
    return result


async def couponstance():
    async with async_playwright() as p:

        if not UID_LIST:
            logging.info("UID Not found")
            return

        browser = await p.chromium.launch(headless=True)
        context = await browser.new_context()
        page = await context.new_page()

        # Get the Coupon Page URL
        full_url = await extract_coupon_link(page)
        if not full_url:
            return

        # Get the Coupon from Coupon Page
        coupon_code = await extract_coupon_code(page, full_url)
        if not coupon_code:
            return

        # Adding Local Coupon version checker
        try:
            with open('latest_coupon.txt', 'r') as f:
                latest_coupon = f.read().strip()
            if latest_coupon == coupon_code:
                logging.info(f"Coupon Same, Exiting !")
                return
        except FileNotFoundError:
            pass

        # IOS 쿠폰 입력
        logging.info(f"Coupon : {coupon_code}")
        redeemed_uids = []

        for UID in UID_LIST:
            # Submit coupon with retry logic
            result = await submit_coupon_with_retry(page, UID, coupon_code)

            # Handle already-used coupon
            if COUPON_MESSAGE_ALREADY_USED in result:
                logging.info(f"Coupon already used for UID: {UID}")
                redeemed_uids.append(UID)
            elif COUPON_MESSAGE_COOLDOWN not in result:
                logging.info(f"Success or other result for UID {UID}: {result}")
                redeemed_uids.append(UID)

            # Clean up
            await human_like_delay(5000, 10000)  # Delay between UIDs

        logging.info(f"Redeemed or processed UIDs: {redeemed_uids}")

        # Update Coupon to Local Coupon file if Different or Not Exist
        with open('latest_coupon.txt', 'w') as f:
            f.write(coupon_code)
        await browser.close()


asyncio.run(couponstance())
