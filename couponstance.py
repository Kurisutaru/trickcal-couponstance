# For failed / retry UID Read Write Utils
def read_failed_ids() -> list[str]:
    """
    Return the list of previously‑failed UIDs stored in `filename`.
    If the file does not exist, an empty list is returned.
    """
    try:
        with open(FAILED_FILE_PATH, "r", encoding="utf-8") as f:
            return [line.rstrip() for line in f if line.strip()]
    except FileNotFoundError:
        return []


def append_failed_id(uid: str) -> None:
    """
    Append a single UID to `filename`.  The line is terminated with a
    newline so that successive cron jobs can read the file back later.
    """
    # 'ab' would force binary mode; use text mode so we get proper \n.
    with open(FAILED_FILE_PATH, "a", encoding="utf-8") as f:
        f.write(f"{uid}\n")


def append_failed_ids(uids: list[str]) -> None:
    """Append *each* UID in `uids` to `filename`, one per line."""
    with open(FAILED_FILE_PATH, "w", encoding="utf-8") as f:
        f.writelines(f"{uid}\n" for uid in uids)


# Format following Trickcal Naver post
def _korean_to_utc_epoch_discord(korean: str, tz_src: str = 'Asia/Seoul') -> str:
    """
    Convert "7월 28일 18:00" or "9월 9일" into a UTC epoch.
    If hour:minute is missing it becomes 00:00.
    """
    # Regex: month/day, optional hour:minute
    _regex = re.compile(
        r'(?P<month>\d+)월\s+'
        r'(?P<day>\d+)일'
        r'(?:\s+(?P<hour>\d{1,2}):(?P<minute>\d{2}))?'  # optional
    )
    m = _regex.search(korean)
    if not m:
        now = datetime.now(tz=tz.gettz(tz_src))
        utc_now = now.astimezone(tz.UTC)
        return f"<t:{int(utc_now.timestamp())}:f>"

    month = int(m.group('month'))
    day = int(m.group('day'))
    hour = int(m.group('hour')) if m.group('hour') else 0
    minute = int(m.group('minute')) if m.group('minute') else 0

    # Guess the correct year – roll over to next year if month < current month
    now = datetime.now(tz=tz.gettz(tz_src))
    year = now.year + (month < now.month)

    local_dt = datetime(year, month, day, hour, minute, tzinfo=tz.gettz(tz_src))
    utc_dt = local_dt.astimezone(tz.UTC)
    if hour == 0 and minute == 0:
        return f"<t:{int(utc_dt.timestamp())}:D>"
    else:
        return f"<t:{int(utc_dt.timestamp())}:f>"


# Get the link
async def extract_coupon_link(page):
    # Navigate to the coupon board
    await page.goto(COUPON_NOTICE_BOARD_URL, wait_until='load')

    # Wait for content to load (adjust selector as needed)
    await page.wait_for_selector('a[class*="post_board_title"]', state='visible')

    # Query for <a> tag with class containing "post_board_title" AND text containing "[쿠폰]"
    post_link_elem = await page.query_selector(f'a[class*="post_board_title"]:has-text("{THREAD_COUPON_TITLE}")')

    if post_link_elem:
        post_href = await post_link_elem.get_attribute('href')
        full_url = BASE_URL + post_href
        logging.info(f"Found coupon link: {full_url}")
        return full_url
    else:
        logging.info("No coupon link found")
        return None


# Assuming you're already on the target page
async def extract_coupon_code_and_stuff(page, full_url):
    # Load page
    await page.goto(full_url, wait_until='load')

    # Coupon Code
    # Step 1: Find the <p> that has a <span> containing "쿠폰 코드" and get its next sibling
    coupon_label_locator = page.locator('p').filter(has_text=COUPON_HEADER).first

    # Ensure the coupon label element is actually found before proceeding
    await coupon_label_locator.wait_for()

    if not await coupon_label_locator.count():
        logging.info(f"❌ '{COUPON_HEADER}' not found in any <p>")
        return None

    # Step 2: Get the very next <p> sibling (adjacent sibling)
    next_p_locator = coupon_label_locator.locator('xpath=following-sibling::p[1]')

    if not await next_p_locator.count():
        logging.info("❌ No next <p> found")
        return None

    # Step 3: Extract text from span inside next <p>
    # Instead of evaluate, use locator to find span and get text
    coupon_code_span_locator = next_p_locator.locator('span').first

    if not await coupon_code_span_locator.count():
        logging.info("❌ No span found in next <p>")
        return None

    coupon_code = await coupon_code_span_locator.text_content()

    if coupon_code and coupon_code.strip():
        coupon_code = coupon_code.strip()
        logging.info(f"✅ Coupon code: {coupon_code}")
    else:
        logging.info("❌ Empty or no span text")
        coupon_code = None

    # Coupon Date
    # Step 1: Find the <p> that has a <span> containing "사용 기한" and get its next sibling
    coupon_date_locator = page.locator('p').filter(has_text=COUPON_CLAIM_DATE).first

    # Ensure the coupon label element is actually found before proceeding
    await coupon_date_locator.wait_for()

    if not await coupon_date_locator.count():
        logging.info(f"❌ '{COUPON_CLAIM_DATE}' not found in any <p>")
        return None

    # Step 2: Get the very next <p> sibling (adjacent sibling)
    next_p_locator = coupon_date_locator.locator('xpath=following-sibling::p[1]')

    if not await next_p_locator.count():
        logging.info("❌ No next <p> found")
        return None

    # Step 3: Extract text from span inside next <p>
    # Instead of evaluate, use locator to find span and get text
    coupon_claim_date_span_locator = next_p_locator.locator('span').first

    if not await coupon_claim_date_span_locator.count():
        logging.info("❌ No span found in next <p>")
        return None

    coupon_date = await coupon_claim_date_span_locator.text_content()

    if coupon_date and coupon_date.strip():
        coupon_date = coupon_date.strip()
        logging.info(f"✅ Coupon claim date: {coupon_date}")
    else:
        logging.info("❌ Empty or no span text")
        coupon_date = None

    # Coupon Image
    coupon_image_locator = page.locator('div[class*="e-component-content-fit"] img')
    coupon_image = None

    if await coupon_image_locator.count() > 0:
        try:
            coupon_image = await coupon_image_locator.first.get_attribute('src')
            if coupon_image:
                logging.info(f"✅ Coupon Image found: {coupon_image}")
            else:
                logging.info("❌ Image element found but no src attribute")
        except Exception as e:
            logging.info(f"❌ Error extracting image: {e}")
    else:
        logging.info("❌ No image found with selector 'div[class*=\"e-component-content-fit\"] img'")

    # Return both coupon code and image
    if coupon_code:
        return {
            'coupon_code': coupon_code,
            'coupon_date': coupon_date,
            'coupon_image': coupon_image
        }
    else:
        return None


async def human_like_delay(min_ms=100, max_ms=500):
    """Add a random delay to mimic human behavior."""
    await asyncio.sleep(random.uniform(min_ms / 1000, max_ms / 1000))


async def submit_coupon(page, uid, coupon_code):
    """Submit coupon for a given UID."""
    logging.info(f"Entrying Coupon for ID: {uid}")
    await page.goto(IOS_COUPON_URL, wait_until='domcontentloaded')

    # Simulate human-like behavior
    await human_like_delay(500, 1500)
    await page.mouse.move(random.randint(100, 500), random.randint(100, 500))
    await page.locator('#UserId').type(uid, delay=random.randint(50, 150))
    await human_like_delay(300, 1000)
    await page.locator('#CouponCode').type(coupon_code, delay=random.randint(50, 150))

    await human_like_delay(500, 1500)
    await page.click('button[onclick="CouponSubmit()"]')
    await human_like_delay(1000, 3000)

    # Get result message
    result = await page.locator('#result-message').text_content()
    logging.info(f"Result for UID {uid}: {result}")
    return result


async def submit_coupon_with_retry(page, uid, coupon_code):
    """Submit coupon with retry logic for cooldown."""
    for attempt in range(MAX_RETRIES):
        result = await submit_coupon(page, uid, coupon_code)
        if "쿨타임" in result:
            wait_time = (2 ** attempt) * 30  # Exponential backoff: 30s, 60s, 120s
            logging.info(
                f"Cooldown detected for UID {uid}, attempt {attempt + 1}/{MAX_RETRIES}. Waiting {wait_time} seconds...")
            await human_like_delay(wait_time * 1000, (wait_time + 5) * 1000)
        else:
            return result
    logging.error(f"Failed to submit coupon for UID {uid} after {MAX_RETRIES} attempts")
    FAILED_UID_LIST.append(uid)
    return result


async def main_coupon_submit(page, coupon_code):
    # IOS 쿠폰 입력
    logging.info(f"Coupon : {coupon_code}")
    redeemed_uids = []

    for UID in UID_LIST:
        # Submit coupon with retry logic
        result = await submit_coupon_with_retry(page, UID, coupon_code)

        # Handle already-used coupon
        if COUPON_MESSAGE_ALREADY_USED in result:
            logging.info(f"Coupon already used for UID: {UID}")
        elif COUPON_MESSAGE_COOLDOWN not in result:
            logging.info(f"Success or other result for UID {UID}: {result}")

        # Adding to redeemed uid list
        redeemed_uids.append(UID)
        # try to remove from failed uid list, ignore if not exist
        [FAILED_UID_LIST.remove(elem) for elem in [UID] if elem in FAILED_UID_LIST]
        # Clean up
        await human_like_delay(5000, 10000)  # Delay between UIDs

    logging.info(f"Redeemed or processed UIDs: {redeemed_uids}")
    if len(FAILED_UID_LIST) > 0:
        append_failed_ids(FAILED_UID_LIST)
        logging.info(f"Found failed id writing into file for next run.")
    else:
        # If no failed id found
        append_failed_ids([])


